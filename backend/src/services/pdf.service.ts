import PDFDocument from 'pdfkit';

// ─── Inquiry PDF ─────────────────────────────────────────────────────────────

export interface InquiryDocumentData {
    referenceNumber: string;
    clientName: string;
    clientEmail: string;
    clientPhone?: string;
    serviceRequired: string;
    timelinePreference?: string;
    projectDescription?: string;
    internalComments?: string;
    consultantName?: string;
    consultantEmail?: string;
    status: string;
    createdAt: string;
}

const renderInquiryPage = (doc: any, data: InquiryDocumentData) => {
    // Header
    doc.fillColor('#333333').font('Helvetica-Bold').fontSize(20).text('GASCART - Professional Consultation Inquiry', { align: 'center' });
    doc.moveDown();
    doc.fontSize(10).fillColor('#666666').text(`Reference: ${data.referenceNumber}`, { align: 'right' });
    doc.text(`Date: ${new Date(data.createdAt).toLocaleDateString()}`, { align: 'right' });
    doc.moveDown();

    // Consultation Info
    doc.fontSize(14).fillColor('#1a1a2e').text('Service Details', { underline: true });
    doc.fontSize(12).fillColor('#333333').text(`Service Required: ${data.serviceRequired}`);
    if (data.timelinePreference) doc.fontSize(12).text(`Timeline: ${data.timelinePreference}`);
    doc.moveDown();

    // Client Info
    doc.fontSize(14).fillColor('#1a1a2e').text('Client Information', { underline: true });
    doc.fontSize(12).fillColor('#333333').text(`Name: ${data.clientName}`);
    doc.text(`Email: ${data.clientEmail}`);
    if (data.clientPhone) doc.text(`Phone: ${data.clientPhone}`);
    doc.moveDown();

    // Expert Info
    doc.fontSize(14).fillColor('#1a1a2e').text('Assigned Expert', { underline: true });
    if (data.consultantName) {
        doc.fontSize(12).fillColor('#333333').text(`Expert: ${data.consultantName}`);
        doc.text(`Email: ${data.consultantEmail || 'N/A'}`);
    } else {
        doc.fontSize(12).fillColor('#e67e22').text('Status: Unassigned (Admin to Assign)');
    }
    doc.moveDown();

    // Project Details
    if (data.projectDescription) {
        doc.fontSize(14).fillColor('#1a1a2e').text('Project Brief', { underline: true });
        doc.fontSize(10).fillColor('#444444').text(data.projectDescription, { align: 'justify' });
        doc.moveDown();
    }

    // Internal Notes
    if (data.internalComments) {
        doc.fontSize(14).fillColor('#2c3e50').text('Internal Admin Notes (Confidential)', { underline: true });
        doc.fontSize(10).fillColor('#444444').text(data.internalComments, { align: 'justify' });
        doc.moveDown();
    }

    // Footer
    const bottom = doc.page.height - 80;
    doc.fontSize(8).fillColor('#999999').text(
        'This is a formal consultation inquiry request generated by GASCART. Confidentiality of client information and project briefs is maintained under standard platform privacy terms.',
        50,
        bottom,
        { align: 'center', width: 500 }
    );
};

export const generateInquiryPDF = async (data: InquiryDocumentData): Promise<Buffer> => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({ margin: 50 });
        const buffers: Buffer[] = [];

        doc.on('data', buffers.push.bind(buffers));
        doc.on('end', () => resolve(Buffer.concat(buffers)));
        doc.on('error', reject);

        renderInquiryPage(doc, data);
        doc.end();
    });
};

export const generateBulkInquiryPDF = async (items: InquiryDocumentData[]): Promise<Buffer> => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({ margin: 50 });
        const buffers: Buffer[] = [];

        doc.on('data', buffers.push.bind(buffers));
        doc.on('end', () => resolve(Buffer.concat(buffers)));
        doc.on('error', reject);

        items.forEach((data, index) => {
            if (index > 0) doc.addPage();
            renderInquiryPage(doc, data);
        });

        doc.end();
    });
};


// ─── RFQ PDF ─────────────────────────────────────────────────────────────────

export interface RFQDocumentData {
    rfqId: string;
    productName: string;
    submittedFields: Record<string, any>;
    userEmail: string;
    full_name?: string;
    company_name?: string;
    createdAt: string;
}

const renderRFQPage = (doc: any, data: RFQDocumentData) => {
    // Header
    doc.fillColor('#333333').font('Helvetica-Bold').fontSize(20).text('GASCART - Technical Enquiry', { align: 'center' });
    doc.moveDown();
    doc.fontSize(10).fillColor('#666666').text(`Enquiry ID: ${data.rfqId}`, { align: 'right' });
    doc.text(`Date: ${new Date(data.createdAt).toLocaleDateString()}`, { align: 'right' });
    doc.moveDown();

    // Product Info
    doc.fontSize(14).fillColor('#1a1a2e').text('Industrial Asset Details', { underline: true });
    doc.fontSize(12).fillColor('#333333').text(`Asset Name: ${data.productName}`);
    doc.moveDown();

    // Customer Info
    doc.fontSize(14).fillColor('#1a1a2e').text('Client Information', { underline: true });
    doc.fontSize(12).fillColor('#333333').text(`Email: ${data.userEmail}`);
    if (data.full_name) doc.fontSize(12).text(`Name: ${data.full_name}`);
    if (data.company_name) doc.fontSize(12).text(`Company: ${data.company_name}`);
    doc.moveDown();

    // Technical Specifications
    doc.fontSize(14).fillColor('#1a1a2e').text('Technical Requirements', { underline: true });
    doc.moveDown(0.5);

    Object.entries(data.submittedFields).forEach(([label, value]) => {
        // Skip metadata fields if they exist
        if (['enquiry_id', 'company_name', 'item_quantity', 'item_price'].includes(label)) return;
        
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#333333').text(`${label}: `, { continued: true });
        doc.font('Helvetica').fillColor('#444444').text(`${value}`);
        doc.moveDown(0.5);
    });

    // Footer
    const bottom = doc.page.height - 80;
    doc.fontSize(8).fillColor('#999999').text(
        'This is a system-generated technical requisition document. Confidentiality of engineering parameters is maintained under standard GASCART NDA terms.',
        50,
        bottom,
        { align: 'center', width: 500 }
    );
};

