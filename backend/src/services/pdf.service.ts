// ─── Invoice PDF ──────────────────────────────────────────────────────────────

export interface InvoiceOrderItem {
    quantity: number;
    price_at_purchase: number;
    product?: { name?: string; advance_payment_percentage?: number };
}

export interface InvoiceShippingAddress {
    full_name?: string;
    address_line1?: string;
    city?: string;
    state?: string;
    postal_code?: string;
    zip_code?: string;
    phone?: string;
}

export interface InvoiceData {
    orderId: string;
    orderOrderId?: string; // Optional support for different key names if needed
    createdAt: string;
    paymentStatus: string;
    razorpayPaymentId?: string;
    totalAmount: number;
    paidAmount?: number;
    balanceDue?: number;
    orderItems: InvoiceOrderItem[];
    shippingAddress: InvoiceShippingAddress;
    profile?: { full_name?: string; email?: string };
}

export const generateInvoicePDF = (data: InvoiceData): Promise<Buffer> => {
    return new Promise((resolve, reject) => {
        // Create document with strict bottom margin to prevent auto-breaks too early
        const doc = new PDFDocument({ 
            margin: 50,
            autoFirstPage: true
        });
        const chunks: Buffer[] = [];

        doc.on('data', (chunk) => chunks.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(chunks)));
        doc.on('error', reject);

        const shortId = data.orderId.slice(-8).toUpperCase();

        renderInvoice(doc, data);

        doc.end();
    });
};

